#!/usr/bin/env node
// Generates dist/tokens.css (CSS variables, light + dark) and dist/AeroTokens.swift,
// and fails if any WCAG contrast check in tokens.json is not met.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));

const lum = (hex) => {
  const c = hex.replace("#", "").match(/../g).map((x) => parseInt(x, 16) / 255);
  const l = c.map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * l[0] + 0.7152 * l[1] + 0.0722 * l[2];
};
export const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
};

let failed = 0;
const report = [];
for (const theme of ["dark", "light"]) {
  for (const [fg, bg, min] of t.contrastChecks) {
    const r = contrast(t.color[theme][fg], t.color[theme][bg]);
    const ok = r >= min;
    if (!ok) failed++;
    report.push(`${ok ? "ok  " : "FAIL"} ${theme.padEnd(5)} ${fg} on ${bg}: ${r.toFixed(2)} (min ${min})`);
  }
}
console.log(report.join("\n"));

const kebab = (s) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());
const rgb = (hex) => hex.replace("#", "").match(/../g).map((x) => parseInt(x, 16)).join(" ");
const vars = (theme) =>
  Object.entries(t.color[theme]).map(([k, v]) => `  --rf-${kebab(k)}: ${rgb(v)};`).join("\n");

const css = `/* Generated by packages/design-tokens/build.mjs — do not edit. */
:root, [data-theme="light"] {
  color-scheme: light;
${vars("light")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${vars("dark").replace(/^/gm, "  ")}
  }
}
[data-theme="dark"] {
  color-scheme: dark;
${vars("dark")}
}
:root {
  --rf-font-sans: ${t.type.fontSans};
  --rf-font-mono: ${t.type.fontMono};
  --rf-radius-sm: ${t.radius.sm}px; --rf-radius-md: ${t.radius.md}px; --rf-radius-lg: ${t.radius.lg}px; --rf-radius-xl: ${t.radius.xl}px;
  --rf-control-h: ${t.control.heightDefault}px; --rf-control-h-lg: ${t.control.heightLarge}px;
  --rf-motion-fast: ${t.motion.fast}ms; --rf-motion-base: ${t.motion.base}ms; --rf-ease: ${t.motion.easing};
}
`;

const swiftColor = (hex) => {
  const [r, g, b] = hex.replace("#", "").match(/../g).map((x) => (parseInt(x, 16) / 255).toFixed(4));
  return `UIColor(red: ${r}, green: ${g}, blue: ${b}, alpha: 1)`;
};
const swift = `// Generated by packages/design-tokens/build.mjs — do not edit.
import SwiftUI
import UIKit

public enum AeroTokens {
${Object.keys(t.color.dark)
  .map(
    (k) => `    public static let ${k} = Color(UIColor { $0.userInterfaceStyle == .dark ? ${swiftColor(t.color.dark[k])} : ${swiftColor(t.color.light[k])} })`
  )
  .join("\n")}

    public enum Space {
${Object.entries(t.space).map(([k, v]) => `        public static let s${k}: CGFloat = ${v}`).join("\n")}
    }
    public enum Radius {
${Object.entries(t.radius).map(([k, v]) => `        public static let ${k}: CGFloat = ${v}`).join("\n")}
    }
    public enum Control {
        public static let height: CGFloat = ${t.control.heightDefault}
        public static let heightLarge: CGFloat = ${t.control.heightLarge}
    }
    public enum Freshness {
        public static let liveSeconds: TimeInterval = ${t.freshness.liveSeconds}
        public static let lostSeconds: TimeInterval = ${t.freshness.lostSeconds}
    }
}
`;

mkdirSync(join(here, "dist"), { recursive: true });
writeFileSync(join(here, "dist/tokens.css"), css);
writeFileSync(join(here, "dist/AeroTokens.swift"), swift);
writeFileSync(join(here, "dist/tokens.json"), JSON.stringify(t, null, 2));
if (failed) {
  console.error(`\n${failed} contrast check(s) failed`);
  process.exit(1);
}
console.log("\nall contrast checks passed; dist/ regenerated");
