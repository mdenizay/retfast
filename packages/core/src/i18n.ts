export const messages: Record<Locale, Record<MessageKey, string>> = { en, tr };
export const locales: Locale[] = ["en", "tr"];

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = messages[locale]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** API hata kodunu kullanıcı metnine çevirir. */
export function errorMessage(locale: Locale, code: string): string {
  const key = `error.${code}` as MessageKey;
  return key in en ? translate(locale, key) : translate(locale, "error.unknown");
}

/** "3 dk", "2 sa" gibi kısa süre. */
export function shortAge(locale: Locale, ms: number): string {
  const s = Math.max(0, Math.round(ms / 1000));
  const u = locale === "tr" ? { s: "sn", m: "dk", h: "sa", d: "g" } : { s: "s", m: "min", h: "h", d: "d" };
  if (s < 60) return `${s} ${u.s}`;
  if (s < 3600) return `${Math.floor(s / 60)} ${u.m}`;
  if (s < 86400) return `${Math.floor(s / 3600)} ${u.h}`;
  return `${Math.floor(s / 86400)} ${u.d}`;
}
