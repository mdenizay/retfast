#!/usr/bin/env python3
"""Generate Tools/cameli-sim-route.gpx — a SYNTHETIC paragliding route near the
Denizli Teleferik upper station (TR) for simulator testing. Not a real flight.

Profile: 2 min on launch (slow walk), take-off, glide, two thermals (circling
+ climbing), cruise glide, landing approach, 2 min on the landing field.
Deterministic (no randomness). Timestamps are 1 s apart so Xcode's GPX
playback reproduces ground speed.
"""
import math, datetime, pathlib

LAUNCH = (37.70804, 29.13508, 1300.0)  # Teleferik upper station (OSM), Bağbaşı
out = []
lat, lon, alt = LAUNCH
heading = 350.0  # N, towards the city
t = datetime.datetime(2026, 11, 4, 9, 0, 0, tzinfo=datetime.timezone.utc)
M_PER_DEG_LAT = 111_320.0

def step(speed, vario, turn=0.0, seconds=1):
    global lat, lon, alt, heading, t
    for _ in range(seconds):
        heading = (heading + turn) % 360
        d = speed
        lat += d * math.cos(math.radians(heading)) / M_PER_DEG_LAT
        lon += d * math.sin(math.radians(heading)) / (M_PER_DEG_LAT * math.cos(math.radians(lat)))
        alt += vario
        t += datetime.timedelta(seconds=1)
        out.append((lat, lon, alt, t))

out.append((lat, lon, alt, t))
step(0.4, 0.0, seconds=120)            # pre-flight on launch
step(6.0, -0.5, seconds=20)            # take-off run / leaving the hill
step(10.0, -1.2, seconds=90)           # glide
step(8.5, 1.8, turn=15.0, seconds=180) # thermal 1 (circling ~24 s/turn)
step(11.0, -1.1, seconds=150)          # cruise
step(8.5, 1.6, turn=-14.0, seconds=150)# thermal 2 (left turns)
step(11.5, -2.2, seconds=300)          # long glide
step(9.0, -1.5, turn=4.0, seconds=60)  # approach
step(4.0, -1.0, seconds=20)            # flare
step(0.3, 0.0, seconds=120)            # on the landing field

lines = ['<?xml version="1.0" encoding="UTF-8"?>',
         '<!-- SYNTHETIC test route generated by Tools/make-sim-route.py. Not a real flight. -->',
         '<gpx version="1.1" creator="Retfast make-sim-route.py" xmlns="http://www.topografix.com/GPX/1/1">',
         '  <metadata><name>Denizli Teleferik synthetic sim route</name><desc>SYNTHETIC simulator data, not a real flight</desc></metadata>']
for la, lo, el, tt in out:
    lines.append(f'  <wpt lat="{la:.6f}" lon="{lo:.6f}"><ele>{el:.1f}</ele><time>{tt.strftime("%Y-%m-%dT%H:%M:%SZ")}</time></wpt>')
lines.append('</gpx>')
path = pathlib.Path(__file__).with_name("cameli-sim-route.gpx")
path.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {path} with {len(out)} points, end {out[-1][0]:.5f},{out[-1][1]:.5f} alt {out[-1][2]:.0f}")
