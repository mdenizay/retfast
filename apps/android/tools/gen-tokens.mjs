#!/usr/bin/env node
// Generates app/src/main/java/com/mizibu/retfast/ui/theme/AeroTokens.kt from
// packages/design-tokens/tokens.json (the single source of truth shared with web and iOS).
// Usage: node apps/android/tools/gen-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, "../../../packages/design-tokens/tokens.json"), "utf8"));
const argb = (hex) => "0xFF" + hex.replace("#", "").toUpperCase();
const scheme = (name, c) =>
  `    val ${name} = AeroColors(\n` +
  Object.entries(c).map(([k, v]) => `        ${k} = Color(${argb(v)})`).join(",\n") +
  `\n    )`;
const props = Object.keys(t.color.dark).map((k) => `    val ${k}: Color`).join("\n");

const out = `// Generated by apps/android/tools/gen-tokens.mjs from packages/design-tokens/tokens.json — do not edit.
package com.mizibu.retfast.ui.theme

import androidx.compose.ui.graphics.Color

data class AeroColors(
${Object.keys(t.color.dark).map((k) => `    val ${k}: Color`).join(",\n")}
)

object AeroTokens {
${scheme("dark", t.color.dark)}

${scheme("light", t.color.light)}

    object Space {
${Object.entries(t.space).map(([k, v]) => `        const val s${k} = ${v}`).join("\n")}
    }
    object Radius {
${Object.entries(t.radius).map(([k, v]) => `        const val ${k} = ${v}`).join("\n")}
    }
    object Control {
        const val height = ${t.control.heightDefault}
        const val heightLarge = ${t.control.heightLarge}
        const val minTouch = ${t.control.minTouch}
    }
    object Freshness {
        const val liveSeconds = ${t.freshness.liveSeconds}
        const val lostSeconds = ${t.freshness.lostSeconds}
    }
}
`;
const dest = join(here, "../app/src/main/java/com/mizibu/retfast/ui/theme");
mkdirSync(dest, { recursive: true });
writeFileSync(join(dest, "AeroTokens.kt"), out);
console.log("wrote AeroTokens.kt");
