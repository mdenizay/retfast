#!/usr/bin/env node
// Generates app/src/main/java/com/mizibu/retfast/ui/theme/Lucide.kt (Compose ImageVectors) from the
// lucide-react package installed for the web app, so Android uses the same icon set as iOS and web.
// Usage: (cd apps/web && npm ci) && node apps/android/tools/gen-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(here, "../../web/node_modules/lucide-react/dist/esm/icons");
const out = join(here, "../app/src/main/java/com/mizibu/retfast/ui/theme/Lucide.kt");

const NAMES = `activity archive armchair arrow-down arrow-down-to-line arrow-left arrow-right arrow-up arrow-up-right
maximize badge-check battery battery-low bell bell-off calendar car chart-column chart-line check chevron-down chevron-left chevron-right
chevron-up circle circle-alert circle-arrow-down circle-arrow-up circle-check circle-dot circle-help circle-pause
circle-stop circle-user circle-x clock clock-alert cloud cloud-alert cloud-off cloud-upload compass copy crosshair
download ellipsis external-link eye eye-off fast-forward flag flask-conical footprints gauge globe hand history
hourglass house inbox info key-round layers list locate locate-fixed locate-off lock lock-keyhole log-out mail map
map-pin map-pin-off menu merge message-square-text minus moon mountain mountain-snow navigation navigation-2
octagon-alert pause pencil phone plane plane-landing plane-takeoff play plus radio refresh-cw rewind rotate-cw route
satellite scan search send settings share shield-alert siren smartphone sparkles square star stethoscope sun sun-moon
thermometer timer trending-down trending-up triangle-alert trophy undo-2 user user-plus user-x users wifi wifi-off
trash-2 wind x zap zap-off`.split(/\s+/).filter(Boolean);

const n = (v) => Number(v ?? 0);
const toPath = ([tag, a]) => {
  switch (tag) {
    case "path": return a.d;
    case "circle": { const r = n(a.r), cx = n(a.cx), cy = n(a.cy); return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`; }
    case "ellipse": { const rx = n(a.rx), ry = n(a.ry), cx = n(a.cx), cy = n(a.cy); return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`; }
    case "line": return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case "polyline": return "M" + a.points.trim().split(/[\s,]+/).reduce((acc, v, i, arr) => (i % 2 ? acc : [...acc, `${v} ${arr[i + 1]}`]), []).join("L");
    case "polygon": return "M" + a.points.trim().split(/[\s,]+/).reduce((acc, v, i, arr) => (i % 2 ? acc : [...acc, `${v} ${arr[i + 1]}`]), []).join("L") + "Z";
    case "rect": {
      const x = n(a.x), y = n(a.y), w = n(a.width), h = n(a.height); let r = n(a.rx ?? a.ry);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      r = Math.min(r, w / 2, h / 2);
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
    default: throw new Error("unsupported element " + tag);
  }
};
const camel = (s) => s.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");

const entries = [];
for (const name of NAMES) {
  let file = join(iconsDir, `${name}.mjs`);
  const alias = readFileSync(file, "utf8").match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/);
  if (alias) file = join(iconsDir, `${alias[1]}.mjs`);
  const mod = await import(pathToFileURL(file).href);
  const paths = mod.__iconData.node.map(toPath);
  entries.push(`    val ${camel(name)}: ImageVector by lazy { icon("${name}", ${paths.map((p) => JSON.stringify(p)).join(", ")}) }`);
}

writeFileSync(out, `// Generated by apps/android/tools/gen-icons.mjs from lucide-react (ISC licence) — do not edit.
package com.mizibu.retfast.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/** Lucide line icons (24 grid, stroke 2, round caps), the shared Retfast icon set. */
@Suppress("unused")
object Lucide {
    private fun icon(name: String, vararg paths: String): ImageVector {
        val b = ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)
        for (d in paths) {
            b.addPath(
                pathData = addPathNodes(d),
                stroke = SolidColor(Color.Black),
                strokeLineWidth = 2f,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round,
            )
        }
        return b.build()
    }

${entries.join("\n")}
}
`);
console.log(`wrote ${entries.length} icons to ${out}`);
